"use strict";

/*
=========================================================
 DON MARTIAL BIG ODD ENGINE
=========================================================

The WebSocket/game server can call publishFromRound(round)
when a generated round qualifies as a BIG ODD.

This engine keeps the BIG ODD records in memory for now.
Later we can move storage to Supabase/PostgreSQL without
changing the REST endpoint contract.

BIG ODD is generated by the game server; the API only
publishes/serves what the engine has received.
=========================================================
*/

const MAX_HISTORY = 1000;
const BIG_ODD_MINIMUM = Number(process.env.BIG_ODD_MINIMUM || 10);

const records = [];
let sequence = 0;

function todayKey(date = new Date()) {
    return date.toISOString().slice(0, 10);
}

function makeId() {
    sequence += 1;
    return `BO-${todayKey()}-${String(sequence).padStart(4, "0")}`;
}

function normalizeStatus(record) {
    if (record.status === "played" || record.status === "running") {
        return record.status;
    }
    return null;
}

function publishFromRound(round) {
    if (!round) return null;

    const multiplier = Number(round.crashMultiplier);
    if (!Number.isFinite(multiplier) || multiplier < BIG_ODD_MINIMUM) {
        return null;
    }

    const roundId = Number(round.roundId);
    const duplicate = records.find(item =>
        item.roundId === roundId ||
        item.id === round.bigOddId
    );

    if (duplicate) return duplicate;

    const createdAt = round.crashedAt || round.createdAt || new Date().toISOString();

    const record = {
        id: round.bigOddId || makeId(),
        roundId: Number.isFinite(roundId) ? roundId : null,
        odd: Number(multiplier.toFixed(2)),
        status: round.status === "RUNNING" ? "running" : "played",
        date: todayKey(new Date(createdAt)),
        createdAt,
        runningAt: round.startedAt || null,
        playedAt: round.crashedAt || null,
        serverTime: new Date().toISOString()
    };

    records.unshift(record);

    if (records.length > MAX_HISTORY) {
        records.length = MAX_HISTORY;
    }

    return record;
}

function updateRoundStatus(roundId, status, extra = {}) {
    const id = Number(roundId);
    const record = records.find(item => Number(item.roundId) === id);

    if (!record) return null;

    if (status === "RUNNING" || status === "running") {
        record.status = "running";
        record.runningAt = extra.runningAt || record.runningAt || new Date().toISOString();
    } else if (status === "CRASHED" || status === "played") {
        record.status = "played";
        record.playedAt = extra.playedAt || record.playedAt || new Date().toISOString();
    }

    record.serverTime = new Date().toISOString();
    return record;
}

function getCurrent() {
    return records.find(item => item.status === "running") || null;
}

function getNext() {
    const future = records
        .filter(item => item.status === null)
        .sort((a, b) => new Date(a.createdAt) - new Date(b.createdAt));

    return future[0] || null;
}

function getUpcoming() {
    return records
        .filter(item => item.status === null)
        .sort((a, b) => new Date(a.createdAt) - new Date(b.createdAt));
}

function getToday() {
    const key = todayKey();
    return records.filter(item => item.date === key);
}

function getHistory() {
    return [...records];
}

function getStats() {
    const today = getToday();
    return {
        total: records.length,
        today: today.length,
        running: records.filter(item => item.status === "running").length,
        played: records.filter(item => item.status === "played").length,
        upcoming: records.filter(item => item.status === null).length
    };
}

module.exports = {
    BIG_ODD_MINIMUM,
    publishFromRound,
    updateRoundStatus,
    getCurrent,
    getNext,
    getUpcoming,
    getToday,
    getHistory,
    getStats
};
